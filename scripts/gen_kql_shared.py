"""Render kql/00_shared.kql from src/anschlussradar/ml/features.py.

Category groups, buffer buckets, minimum transfer times and the history window are
needed both in Python (API, training) and in Data Explorer (TransferFacts, training
export, history counts). They are defined once in Python and generated here, so the
two can never disagree. Run after changing features.py:

  python scripts/gen_kql_shared.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from anschlussradar.ingest.hubs import load_hubs  # noqa: E402
from anschlussradar.ml import features as f  # noqa: E402


def _list(values: tuple[str, ...]) -> str:
    return ", ".join(f'"{v}"' for v in values)


def render() -> str:
    group_cases = ", ".join(
        f'c in ({_list(cats)}), "{group}"' for group, cats in f.CATEGORY_GROUPS.items()
    )
    bucket_cases = ", ".join(
        f'minutes between ({low} .. {high}), "{label}"' for low, high, label in f.BUFFER_BUCKETS
    )
    return "\n".join(
        [
            "// Generated by scripts/gen_kql_shared.py from src/anschlussradar/ml/features.py.",
            "// Do not edit by hand.",
            "",
            '.create-or-alter function with (folder="shared", docstring="Train category group: long, regional, sbahn, other")',
            "CategoryGroup(category:string) {",
            '    let c = toupper(trim(@"\\s+", category));',
            f'    case({group_cases}, "other")',
            "}",
            "",
            '.create-or-alter function with (folder="shared", docstring="Minimum transfer time in minutes")',
            "MinTransferMinutes(in_category:string, out_category:string, cross_level:bool) {",
            f'    iff(CategoryGroup(in_category) == "long" or CategoryGroup(out_category) == "long", {f.MIN_TRANSFER_LONG}, {f.MIN_TRANSFER_DEFAULT})',
            f"    + iff(cross_level, {f.CROSS_LEVEL_EXTRA_MIN}, 0)",
            "}",
            "",
            '.create-or-alter function with (folder="shared", docstring="Planned buffer bucket")',
            "BufferBucket(minutes:int) {",
            f'    case({bucket_cases}, "outside")',
            "}",
            "",
            '.create-or-alter function with (folder="shared", docstring="Days of history behind the count features")',
            "HistoryDays() {",
            f"    {f.HISTORY_DAYS}",
            "}",
            "",
            '.create-or-alter function with (folder="shared", docstring="EVA to station group, from config/hubs.csv")',
            "StationGroups() {",
            f"    datatable(eva:long, group_eva:long) [{_groups()}]",
            "}",
            "",
        ]
    )


def _groups() -> str:
    hubs = load_hubs(ROOT / "config" / "hubs.csv")
    # Only stations that belong to another EVA's group; all others are their own group.
    pairs = [
        f"{h.eva}, {h.group_eva}" for h in sorted(hubs, key=lambda h: h.eva) if h.group_eva != h.eva
    ]
    return ", ".join(pairs)


if __name__ == "__main__":
    target = ROOT / "kql" / "00_shared.kql"
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target}")
