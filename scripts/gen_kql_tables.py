"""Generate kql/01_tables.kql (tables and JSON ingestion mappings) from one column list.

Run after changing a column:  python scripts/gen_kql_tables.py
Keeping table and mapping in one place avoids the classic mismatch bug.
"""

from pathlib import Path

TABLES: dict[str, list[tuple[str, str]]] = {
    "PlannedStops": [
        ("stop_id", "string"),
        ("eva", "long"),
        ("station_name", "string"),
        ("service_date", "datetime"),
        ("category", "string"),
        ("number", "string"),
        ("line", "string"),
        ("operator", "string"),
        ("filter_flag", "string"),
        ("trip_type", "string"),
        ("arr_pt", "datetime"),
        ("dep_pt", "datetime"),
        ("arr_pp", "string"),
        ("dep_pp", "string"),
        ("origin", "string"),
        ("destination", "string"),
        ("arr_path", "dynamic"),
        ("dep_path", "dynamic"),
        ("time_flag", "string"),
        ("observed_at", "datetime"),
    ],
    "StopChangeEvents": [
        ("event_id", "string"),
        ("stop_id", "string"),
        ("eva", "long"),
        ("endpoint", "string"),
        ("observed_at", "datetime"),
        ("arr_ct", "datetime"),
        ("arr_cp", "string"),
        ("arr_cs", "string"),
        ("arr_clt", "datetime"),
        ("dep_ct", "datetime"),
        ("dep_cp", "string"),
        ("dep_cs", "string"),
        ("dep_clt", "datetime"),
        ("category", "string"),
        ("number", "string"),
        ("messages", "dynamic"),
        ("time_flag", "string"),
    ],
    "WeatherHourly": [
        ("eva", "long"),
        ("observed_hour", "datetime"),
        ("temperature", "real"),
        ("precipitation", "real"),
        ("wind_speed", "real"),
        ("wind_gust_speed", "real"),
        ("visibility", "real"),
        ("cloud_cover", "real"),
        ("condition", "string"),
        ("source_id", "long"),
        ("fetched_at", "datetime"),
    ],
    "IngestionLog": [
        ("run_id", "string"),
        ("endpoint", "string"),
        ("eva", "long"),
        ("status_code", "int"),
        ("latency_ms", "int"),
        ("response_bytes", "long"),
        ("events_written", "int"),
        ("error_text", "string"),
        ("fetched_at", "datetime"),
    ],
}


def render() -> str:
    out = [
        "// Generated by scripts/gen_kql_tables.py. Do not edit by hand.",
        "// Silver tables and their JSON ingestion mappings.",
        "",
    ]
    for table, cols in TABLES.items():
        schema = ", ".join(f"{c}:{t}" for c, t in cols)
        out.append(f".create-merge table {table} ({schema})")
        out.append("")
        mapping = ",".join(f'{{"column":"{c}","Properties":{{"Path":"$.{c}"}}}}' for c, _ in cols)
        out.append(f'.create-or-alter table {table} ingestion json mapping "{table}_json"')
        out.append(f"'[{mapping}]'")
        out.append("")
    out += [
        "// Keep raw-ish silver data for 400 days; the bronze files stay in Blob Storage.",
        ".alter-merge table StopChangeEvents policy retention softdelete = 400d",
        ".alter-merge table PlannedStops policy retention softdelete = 400d",
        ".alter-merge table IngestionLog policy retention softdelete = 90d",
        ".alter-merge table WeatherHourly policy retention softdelete = 400d",
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "kql" / "01_tables.kql"
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target}")
