"""Build the outline of Germany for the network map (web/src/lib/germanyMap.ts).

Source: Natural Earth "Admin 1 – States, Provinces" 1:10m, public domain
(https://www.naturalearthdata.com). Download it once, then run:

    python scripts/build_germany_map.py ne_10m_admin_1_states_provinces_lakes.geojson

The map uses a plain equirectangular projection with longitudes shortened by
cos(51°). Over Germany that is close enough to what people expect, and the web
app can place a station from its latitude and longitude with two lines of code.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "src" / "lib" / "germanyMap.ts"

LON0, LAT0 = 5.8, 55.1  # top left corner
KX = math.cos(math.radians(51.0)) * 100
KY = 100.0
TOLERANCE = 0.015  # degrees, about 1.5 km
MIN_AREA = 0.002  # square degrees: drops the small islands

Point = tuple[float, float]


def rdp(points: list[Point], eps: float) -> list[Point]:
    """Ramer–Douglas–Peucker line simplification."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-12
    best, index = 0.0, 0
    for i in range(1, len(points) - 1):
        x, y = points[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, index = d, i
    if best <= eps:
        return [points[0], points[-1]]
    return rdp(points[: index + 1], eps)[:-1] + rdp(points[index:], eps)


def area(ring: list[Point]) -> float:
    return (
        abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:], strict=False))) / 2
    )


def project(lon: float, lat: float) -> Point:
    return (lon - LON0) * KX, (LAT0 - lat) * KY


def path(polygons: list[list[list[list[float]]]]) -> str:
    parts = []
    for polygon in polygons:
        for ring in polygon[:1]:  # outer ring only; German states have no holes worth drawing
            pts = [(p[0], p[1]) for p in ring]
            if area(pts) < MIN_AREA:
                continue
            # A closed ring starts and ends on the same point: split it at the point
            # farthest from the start, simplify both halves, join them again.
            far = max(range(len(pts)), key=lambda i: math.dist(pts[0], pts[i]))
            simple = rdp(pts[: far + 1], TOLERANCE)[:-1] + rdp(pts[far:], TOLERANCE)
            if len(simple) < 4:
                continue
            xy = [project(lon, lat) for lon, lat in simple]
            parts.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in xy) + "Z")
    return "".join(parts)


def main(source: str) -> None:
    data = json.loads(Path(source).read_text(encoding="utf-8"))
    states = []
    for f in data["features"]:
        props = f["properties"]
        if props.get("adm0_a3") != "DEU":
            continue
        geom = f["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        states.append((props["name"], path(polys)))
    states.sort()
    width = round((15.1 - LON0) * KX)
    height = round((LAT0 - 47.2) * KY)
    lines = [
        "// Generated by scripts/build_germany_map.py from Natural Earth (public domain).",
        "// Do not edit by hand.",
        "",
        f"export const MAP_WIDTH = {width};",
        f"export const MAP_HEIGHT = {height};",
        "",
        "/** x, y on the map for a latitude and longitude. */",
        "export function project(lat: number, lon: number): [number, number] {",
        f"  return [(lon - {LON0}) * {KX:.4f}, ({LAT0} - lat) * {KY}];",
        "}",
        "",
        "export const STATES: { name: string; d: string }[] = [",
    ]
    lines += [
        f"  {{ name: {json.dumps(n, ensure_ascii=False)}, d: {json.dumps(d)} }}," for n, d in states
    ]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(states)} states, {OUT.stat().st_size // 1024} KB -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
